export function convertRecordsToCSV(records: PatientRecord[]): string {
  const headers = [
    'Record_ID',
    'Patient_Persona',
    'Age_Group',
    'Visit_Type',
    'Service_Line',
    'Year',
    'Patient_Satisfaction',
    'Communication_Rating',
    'Followup_Compliance',
    'Portal_Usage',
    'Readmission_Risk',
    'AI_Risk_Flag',
    'Comment',
  ];

  const rows = records.map((r) => [
    r.Record_ID,
    `"${r.Patient_Persona.replace(/"/g, '""')}"`,
    `"${r.Age_Group}"`,
    `"${r.Visit_Type}"`,
    `"${r.Service_Line}"`,
    r.Year,
    r.Patient_Satisfaction,
    r.Communication_Rating,
    r.Followup_Compliance,
    r.Portal_Usage,
    `"${r.Readmission_Risk}"`,
    `"${r.AI_Risk_Flag}"`,
    `"${r.Comment.replace(/"/g, '""')}"`,
  ]);

  return [headers.join(','), ...rows.map((row) => row.join(','))].join('\n');
}
